/**
 * docs/modules.md, generated.
 *
 * Generated rather than hand-written so it cannot drift from the catalog. The
 * unmapped-routes section at the end is the honest coverage boundary: routes
 * the crawl reached that produced no catalogued action.
 */

import type { CatalogIndex, CatalogIndexEntry } from '../catalog/index-build.js';

function moduleSection(module: string, entries: CatalogIndexEntry[]): string {
  const rows = entries
    .map(
      (entry) =>
        `| \`${entry.id}\` | ${entry.name} | ${entry.status} | ${entry.destructive ? 'yes' : 'no'} |`,
    )
    .join('\n');

  return `## ${module}

| id | name | verification | destructive |
|---|---|---|---|
${rows}
`;
}

export function buildModulesDoc(index: CatalogIndex, routes: string[]): string {
  const byModule = new Map<string, CatalogIndexEntry[]>();
  for (const entry of index.actions) {
    const existing = byModule.get(entry.module);
    if (existing) existing.push(entry);
    else byModule.set(entry.module, [entry]);
  }

  const modules = [...byModule.keys()].sort();

  // A route counts as covered when some action id starts with a module that the
  // route path mentions, or when the route appears in an action's id namespace.
  const covered = (route: string): boolean =>
    index.actions.some(
      (entry) =>
        route.toLowerCase().includes(entry.module.toLowerCase()) ||
        entry.module.toLowerCase().includes(route.replace(/^\//, '').split('/')[0] ?? '\u0000'),
    );

  const unmapped = routes.filter((route) => !covered(route)).sort();

  const header = `# Modules and routes

Generated by \`pnpm build:docs\` — do not edit by hand.

${index.count} action(s) catalogued across ${modules.length} module(s): \
${index.by_status.verified} verified, ${index.by_status.observed} observed, \
${index.by_status.inferred} inferred.

Verification means exactly what \`README.md\` says it means. \`verified\` entries were
executed against a real account; \`observed\` entries were seen in real traffic but
never executed; \`inferred\` entries were derived without captured traffic.
`;

  const sections = modules.map((module) => moduleSection(module, byModule.get(module) ?? []));

  const unmappedSection = `## Routes with no catalogued action

${
    unmapped.length === 0
      ? 'Every discovered route produced at least one catalogued action.'
      : `These routes were reached by the crawl but produced no entry. They are the coverage boundary:

${unmapped.map((route) => `- \`${route}\``).join('\n')}`
  }
`;

  return [header, ...sections, unmappedSection].join('\n');
}
